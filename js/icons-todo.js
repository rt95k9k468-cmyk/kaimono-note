  KEYS.forEach(([key, words]) => { LABELS[key] = NAMES[key.slice(3)] || words[0]; });

  const ORDER = KEYS.map(([key]) => key)
    .concat(Object.keys(ICONS).filter((k) => !KEYS.some(([key]) => key === k)));

  /* 引くための表。長い言葉から先に当てます——「買い物」と「買う」が
     どちらも当たるとき、長いほうが言い当てている見込みが高いので。 */
  const KANJI = /[㐀-鿿]/;
  const FLAT = KEYS
    .flatMap(([name, words]) => words.map((w) => {
      const k = KN.util.foldKana(w);
      /* 2文字のひらがなは、**短い題のときだけ**当てます（4文字まで）。
         買うものの辞書で「ぱす」（くれよん）が「ぱすわーど」に当たっていた、
         あの事故と同じことをここで繰り返さないため。漢字は2文字でも名を
         成すので通します。 */
      return [k, name, k.length < 3 && !KANJI.test(k)];
    }))
    .sort((a, b) => b[0].length - a[0].length);

  /** 題に合う絵の**名前**。当てはまらなければ ""。 */
  function findKey(name) {
    const n = KN.util.foldKana(String(name || ""));
    if (!n) return "";
    for (const [k, key, short] of FLAT) {
      if (short && n.length > 4) continue;
      if (n.includes(k)) return key;
    }
    return "";
  }

  /** 同じことを、絵（SVGの文字列）で返します。 */
  function find(name) {
    const key = findKey(name);
    return key ? ICONS[key] : "";
  }

  /** 名前が指す絵。名前でなければ ""。 */
  const byKey = (key) => (key && ICONS[key]) || "";

  /** ぜんぶ、KEYS の並びで。 */
  const list = () => ORDER.map((key) => ({ key, label: LABELS[key] || key, svg: ICONS[key] }));

  /** 名前か言葉に query を含む絵。 */
  function search(query) {
    const q = KN.util.foldKana(String(query || ""));
    if (!q) return list();
    return list().filter(({ key, label }) => {
      if (KN.util.foldKana(label).includes(q)) return true;
      const entry = KEYS.find(([k]) => k === key);
      return !!entry && entry[1].some((w) => KN.util.foldKana(w).includes(q));
    });
  }

  /** 題から、もしかしてこれ、という名前を良い順に。 */
  function suggest(name, limit) {
    const n = KN.util.foldKana(String(name || ""));
    if (!n) return [];
    const score = new Map();
    const bump = (key, v) => { if ((score.get(key) || 0) < v) score.set(key, v); };
    KEYS.forEach(([key, words]) => {
      words.forEach((w) => {
        const k = KN.util.foldKana(w);
        if (!k) return;
        if (k.length >= 3 || KANJI.test(k)) {
          if (n.includes(k)) bump(key, 2000 + k.length * 10);
          else if (n.length >= 2 && k.includes(n)) bump(key, 1000 + n.length * 10);
        } else if (n === k) bump(key, 2000 + k.length * 10);
      });
    });
    return [...score.entries()]
      .sort((a, b) => b[1] - a[1] || ORDER.indexOf(a[0]) - ORDER.indexOf(b[0]))
      .slice(0, limit || 8)
      .map(([key]) => key);
  }

