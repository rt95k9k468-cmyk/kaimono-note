/* =========================================================
   くらしノート — Icon Design System

   アプリ中のあらゆる絵——買うもの、やること、価格、ダイエット、設定——が
   この一つの仕組みの上に立ちます。「食品用の画風」「用事用の画風」は作りません。
   同じ手が描いた一冊の図鑑に見えること、それだけがここの目的です。

   統一を何で作るか
   ----------------
   絵柄の統一は「気をつけて描く」では保てません。857個ともなればなおさらで、
   描く人（や描く日）が変われば必ずぶれます。だから**構造で縛ります**。

     1. 輪郭線   すべての絵が同じ色・同じ太さの線を持つ
     2. 陰と艶   影は黒13%、艶は白。この二つ以外の陰影を作らない
     3. 色       名前のある色だけを使う。生の16進を書かない
     4. 丸み     角丸は決まった段階からしか選ばない
     5. 版面     インクは 3〜21 に収める（線の太さ込みで 2.5〜21.5）

   この5つが同じなら、シルエットがどれだけ違っても一族に見えます。逆にこの
   5つを外すと、どれだけ丁寧に描いても混ざりません。旧版が480色のリテラルを
   抱えて「なんとなく揃っていない」状態だったのは、3が無かったからです。

   テンプレートの色違いにはしない
   ------------------------------
   ここが用意するのは「ボトルの絵」ではなく「角丸」「円」「影」といった**部品**
   です。洗剤と柔軟剤とシャンプーが同じ形の色違いになるのは手抜きで、
   持ち手の有無、注ぎ口の形、肩の落ち方——実物が違うところは形で描き分けます。
   共通なのは線と光と色の語彙だけ。

   24pxで読めること
   ----------------
   実機での表示は 25px（買うものの行）・28px（価格の行）・34px（タイル）です。
   ここに描き込みは入りません。**輪郭で意味を伝え、色で仲間を伝え、
   細部は「あるように見える」程度に留める**——それが 24 グリッドの作法です。
   ========================================================= */
(function () {
  "use strict";

  const KN = (window.KN = window.KN || {});

  /* ---------------- 1. 線 ---------------- */

  /* 輪郭は一色。ここが揃っていることが、統一感のいちばん大きな取り分です。
     真っ黒ではなく茶を含んだ暗色——食べものと日用品が並ぶ画面で、純黒は硬く、
     プラスチックのように見えます。

     CSS 変数にしてあるのは暗い画面のためです。旧版のアイコンは色が固定で、
     ダークテーマでは牛乳や卵のような白いものがカードに溶けていました
     （それを誤魔化すために .p-icon に drop-shadow が一段かかっています）。
     線があれば影は要りません。 */
  const LINE = "var(--ic-line,#4a423b)";

  /* 24 グリッド上で 1。25px 表示でおよそ 1.04px、2倍画面で 2px の実線になります。
     0.8 まで細めると 34px のタイルで頼りなく、1.2 まで太らせると 25px の行で
     絵が線に埋まります。 */
  const LINE_W = 1;

  /* ---------------- 2. 陰と艶 ---------------- */

  /* 影は「黒を薄く重ねる」だけ。色ごとに影の色を作ると、絵ごとに光源が
     ずれます。一枚の黒で通せば、857個すべてで光が同じ側から当たります。 */
  const SHADE = ".13";     // 面の陰。右下に置く
  const SHADE_S = ".08";   // ごく浅い陰。白いものに使う
  const GLOSS = ".55";     // 丸いものの艶
  const GLOW = ".3";       // 広い面の白おき

  /* 光は左上から。全アイコンで同じ。 */
  const LIGHT_X = 9.2, LIGHT_Y = 9.6;

  /* ---------------- 3. 色 ---------------- */

  /* 名前のある色だけを使います。生の 16 進をアイコンの中に書いたら、それは
     この仕組みから外れたということです。

     各系統は base と D（深い方）の対。D は縁・蓋・へた・影に落ちない造形上の
     暗部に使います（面の陰は上の SHADE が持つので、D を影として使わないこと）。 */
  const C = {
    /* 暖色 */
    red:    "#e8594b", redD:    "#c13d33",   // トマト・りんご・肉・危険
    coral:  "#f0776a", coralD:  "#cf5245",
    orange: "#f2903f", orangeD: "#d16d1c",   // にんじん・みかん・注意
    amber:  "#f5c04a", amberD:  "#dc9a1e",   // 卵黄・チーズ・バナナ
    /* 緑 */
    lime:   "#96c85a", limeD:   "#6fa338",   // 葉物・新しいもの
    green:  "#4fa863", greenD:  "#33854a",   // 野菜・植物・完了
    forest: "#2f8f5b", forestD: "#1f6f44",   // アプリの主色に連なる緑
    /* 寒色 */
    teal:   "#3fb3a6", tealD:   "#22907f",
    sky:    "#63b0e8", skyD:    "#3684c6",   // 水・空・冷たいもの
    blue:   "#4d80d6", blueD:   "#2f5cb0",
    indigo: "#6a6fc9", indigoD: "#494ea3",   // 夜・睡眠
    /* 紫・桃 */
    violet: "#a377d8", violetD: "#7d4fb5",
    pink:   "#ef8fb0", pinkD:   "#d1648c",   // 肉・桃・赤ちゃん
    /* 茶・生成り */
    brown:  "#b5793f", brownD:  "#8c5a2b",   // 木・パン・段ボール
    tan:    "#dba869", tanD:    "#b7823f",
    cream:  "#f4e6c8", creamD:  "#dcc79a",   // 生地・紙袋・ごはん
    /* 無彩色 */
    paper:  "#eff3f6", paperD:  "#ccd8e1",   // 白いもの（牛乳・卵・ティッシュ）
    grey:   "#b9c3c9", greyD:   "#8d989f",
    steel:  "#8e9ba4", steelD:  "#65727b",   // 金属・刃物・機械
    ink:    "#4a423b", inkD:    "#332e29",   // 画面・黒いもの
    white:  "#ffffff",
  };

  /* ---------------- 4. 丸み ---------------- */

  /* 角丸はこの段階からしか選びません。中間の値を使い始めた時点で、丸みは
     揃わなくなります。 */
  const R = { xs: .6, sm: 1, md: 1.6, lg: 2.4, xl: 3.4, full: 99 };

  /* ---------------- 部品 ---------------- */

  /* ここにあるのは「ボトル」でも「箱」でもなく、角丸・円・楕円・自由曲線の
     四つだけです。絵そのものは各アイコンが自分で組み立てます——共通部品を
     絵の単位まで太らせると、洗剤と柔軟剤が色違いになります。 */

  const ex = (o) => (o ? " " + o : "");

  /** 角丸。線が付きます。 */
  const r = (x, y, w, h, rad, fill, o) =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rad}" fill="${fill}"${ex(o)}/>`;

  /** 円。線が付きます。 */
  const c = (cx, cy, rad, fill, o) =>
    `<circle cx="${cx}" cy="${cy}" r="${rad}" fill="${fill}"${ex(o)}/>`;

  /** 楕円。線が付きます。 */
  const e = (cx, cy, rx, ry, fill, o) =>
    `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}"${ex(o)}/>`;

  /** 自由曲線。線が付きます。 */
  const p = (d, fill, o) =>
    `<path d="${d}" fill="${fill}"${ex(o)}/>`;

  /* 線の付かないもの ------------------------------------------------
     内側の模様・陰・艶には輪郭を描きません。24px で内側にまで線を引くと、
     絵が黒く潰れます。 */
  const NL = 'stroke="none"';

  /** 線なしの自由曲線（内側の模様） */
  const pn = (d, fill, o) => `<path d="${d}" fill="${fill}" ${NL}${ex(o)}/>`;
  /** 線なしの角丸 */
  const rn = (x, y, w, h, rad, fill, o) =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rad}" fill="${fill}" ${NL}${ex(o)}/>`;
  /** 線なしの円 */
  const cn = (cx, cy, rad, fill, o) => `<circle cx="${cx}" cy="${cy}" r="${rad}" fill="${fill}" ${NL}${ex(o)}/>`;
  /** 線なしの楕円 */
  const en = (cx, cy, rx, ry, fill, o) =>
    `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}" ${NL}${ex(o)}/>`;

  /* 内側の線 --------------------------------------------------------
     ラベルの文字、ほうきの穂、にんじんの筋。輪郭とは別の、細い書き込みです。
     輪郭線（1.0）より必ず細くします——同じ太さで引くと、内と外の区別が
     つかなくなって絵が潰れます。 */
  const ln = (d, color, w, op) =>
    `<path d="${d}" fill="none" stroke="${color}" stroke-width="${w || .9}"` +
    (op ? ` stroke-opacity="${op}"` : "") + ` stroke-linecap="round" stroke-linejoin="round"/>`;

  /* 陰 ------------------------------------------------------------- */

  /** 面の陰。形の右下に重ねます。黒一枚なので、下の色が何であっても馴染みます。 */
  const sh = (d, op) => `<path d="${d}" fill="#000" opacity="${op || SHADE}" ${NL}/>`;
  /** 角丸の陰 */
  const shR = (x, y, w, h, rad, op) =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rad}" fill="#000" opacity="${op || SHADE}" ${NL}/>`;

  /* 艶 ------------------------------------------------------------- */

  /** 丸いものの艶。位置は全アイコン共通なので、光源がぶれません。 */
  const gloss = (cx, cy, rx, ry, rot) =>
    `<ellipse cx="${cx == null ? LIGHT_X : cx}" cy="${cy == null ? LIGHT_Y : cy}" ` +
    `rx="${rx || 2.2}" ry="${ry || 1.4}" fill="#fff" opacity="${GLOSS}" ${NL} ` +
    `transform="rotate(${rot == null ? -32 : rot} ${cx == null ? LIGHT_X : cx} ${cy == null ? LIGHT_Y : cy})"/>`;

  /** 広い面に置く白。ラベル面やガラス面を「平らでない」ものに見せます。 */
  const glow = (d, op) => `<path d="${d}" fill="#fff" opacity="${op || GLOW}" ${NL}/>`;

  /* ---------------- 組み立て ---------------- */

  /* 旧版と同じ器に収めます。viewBox は 24 のまま、class も .p-icon のまま——
     CSS も試験もこの二つを見ているので、中身だけが入れ替わる形にします。

     is-v2 が一つだけ増えます。旧い絵と混ざっているあいだ、「輪郭線があるので
     drop-shadow が要らない側」を CSS から指せるようにするためのものです。
     .p-icon を見ている既存の選択子はそのまま当たります。 */
  const icon = (...parts) =>
    `<svg class="p-icon is-v2" viewBox="0 0 24 24" fill="none" aria-hidden="true">` +
    `<g stroke="${LINE}" stroke-width="${LINE_W}" stroke-linejoin="round" stroke-linecap="round">` +
    parts.join("") +
    `</g></svg>`;

  KN.iconSystem = {
    C, R, LINE, LINE_W, SHADE, SHADE_S, GLOSS, GLOW, LIGHT_X, LIGHT_Y,
    icon, r, c, e, p, rn, cn, en, pn, ln, sh, shR, gloss, glow, NL,
  };
})();
